"""Strict contracts for the controlled clinical-case record module.

This surface stores human-authored records, reviews, and feedback only.  It
does not expose a diagnosis, prescription, recommendation, or generated
clinical conclusion contract.
"""

from __future__ import annotations

from typing import Literal

from pydantic import ConfigDict, Field, field_validator, model_validator

from rick_contracts.base import StrictContractModel


CASE_CONTRACT_VERSION = "clinical-case-contract-v1"
CASE_SCOPE_STATUS = "record_review_feedback_only"

CaseStatus = Literal["open", "reviewed"]
ReviewDecision = Literal["recorded", "needs_revision", "declined"]
FeedbackKind = Literal["correction", "clarification", "quality_issue", "scope_note"]
HypothesisStatus = Literal["open", "supported", "refuted", "deferred"]
EvidenceSourceType = Literal["document", "chunk", "conversation", "external_reference", "manual"]
AgentModelStatus = Literal["authorized", "revoked"]


def _required_text(value: str, *, field_name: str) -> str:
    candidate = value.strip()
    if not candidate:
        raise ValueError(f"{field_name} must not be blank")
    return candidate


class CaseCreateRequest(StrictContractModel):
    """A human-authored record; scope is always server-derived.

    ``record`` remains accepted for clients of the first local draft.  New
    clients should use ``summary`` plus the structured references below.
    """

    title: str = Field(min_length=1, max_length=160)
    summary: str | None = Field(default=None, min_length=1, max_length=20_000)
    record: str | None = Field(default=None, min_length=1, max_length=20_000)
    hypotheses: list["CaseHypothesisInput"] = Field(default_factory=list, max_length=32)
    evidence: list["CaseEvidenceInput"] = Field(default_factory=list, max_length=64)
    tags: list[str] = Field(default_factory=list, max_length=16)

    @field_validator("title", "summary", "record")
    @classmethod
    def normalize_optional_text(cls, value: str | None, info):
        if value is None:
            return None
        return _required_text(value, field_name=info.field_name)

    @field_validator("tags")
    @classmethod
    def normalize_tags(cls, value: list[str]) -> list[str]:
        result: list[str] = []
        for item in value:
            candidate = item.strip()
            if not candidate:
                raise ValueError("tags must not contain blank values")
            if len(candidate) > 64:
                raise ValueError("tags must contain at most 64 characters")
            if candidate not in result:
                result.append(candidate)
        return result

    @model_validator(mode="after")
    def require_summary_or_record(self):
        if self.summary is None and self.record is None:
            raise ValueError("summary or record is required")
        return self


class CaseUpdateRequest(StrictContractModel):
    """Editable human record fields.  Status changes happen through review."""

    title: str | None = Field(default=None, min_length=1, max_length=160)
    summary: str | None = Field(default=None, min_length=1, max_length=20_000)
    record: str | None = Field(default=None, min_length=1, max_length=20_000)
    hypotheses: list["CaseHypothesisInput"] | None = Field(default=None, max_length=32)
    evidence: list["CaseEvidenceInput"] | None = Field(default=None, max_length=64)
    tags: list[str] | None = Field(default=None, max_length=16)

    @field_validator("title", "summary", "record")
    @classmethod
    def normalize_optional_text(cls, value: str | None, info):
        if value is None:
            return None
        return _required_text(value, field_name=info.field_name)

    @field_validator("tags")
    @classmethod
    def normalize_optional_tags(cls, value: list[str] | None) -> list[str] | None:
        if value is None:
            return None
        return CaseCreateRequest.normalize_tags(value)

    @model_validator(mode="after")
    def require_change(self):
        if all(value is None for value in (self.title, self.summary, self.record, self.hypotheses, self.evidence, self.tags)):
            raise ValueError("at least one case field is required")
        return self


class CaseHypothesisInput(StrictContractModel):
    """Human-entered hypothesis metadata; never generated by this module."""

    hypothesis_id: str | None = Field(default=None, min_length=1, max_length=128)
    statement: str = Field(min_length=1, max_length=4_000)
    status: HypothesisStatus = "open"

    @field_validator("hypothesis_id", "statement")
    @classmethod
    def normalize_text(cls, value: str | None, info):
        if value is None:
            return None
        return _required_text(value, field_name=info.field_name)


class CaseHypothesis(StrictContractModel):
    hypothesis_id: str = Field(min_length=1, max_length=128)
    statement: str = Field(min_length=1, max_length=4_000)
    status: HypothesisStatus = "open"


