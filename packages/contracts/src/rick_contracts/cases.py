class CaseRecord(StrictContractModel):
    contract_version: Literal[CASE_CONTRACT_VERSION] = CASE_CONTRACT_VERSION
    clinical_scope_status: Literal[CASE_SCOPE_STATUS] = CASE_SCOPE_STATUS
    case_id: str = Field(min_length=1, max_length=128)
    tenant_id: str = Field(min_length=1, max_length=128)
    workspace_id: str = Field(min_length=1, max_length=128)
    owner_user_id: str = Field(min_length=1, max_length=128)
    title: str = Field(min_length=1, max_length=160)
    summary: str = Field(min_length=1, max_length=20_000)
    record: str = Field(min_length=1, max_length=20_000)
    hypotheses: list[CaseHypothesis] = Field(default_factory=list, max_length=32)
    evidence: list[CaseEvidence] = Field(default_factory=list, max_length=64)
    agent_model: AuthorizedAgentModel | None = None
    tags: list[str] = Field(default_factory=list, max_length=16)
    status: CaseStatus = "open"
    created_by_user_id: str = Field(min_length=1, max_length=128)
    created_at: float = Field(ge=0)
    updated_by_user_id: str = Field(min_length=1, max_length=128)
    updated_at: float = Field(ge=0)
    last_request_id: str | None = Field(default=None, max_length=128)
    review_count: int = Field(default=0, ge=0)
    feedback_count: int = Field(default=0, ge=0)
    last_review_at: float | None = Field(default=None, ge=0)
    last_feedback_at: float | None = Field(default=None, ge=0)


